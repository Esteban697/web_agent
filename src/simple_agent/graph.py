"""LangGraph agent with Trustcall-based structured long-term memory and improved retrieval.

Improvements included:
1. Trustcall structured save/update using WebJourneyMemory schema.
2. Compact retrieval field `search_text` generated by Trustcall.
3. Broader recall strategy: switch between semantic search and history-style listing.
4. Retrieval filters/ranking in code for product-centric memories.
5. Recalled memory summaries are prepended to model-visible messages before the run.
"""

from __future__ import annotations

from langchain.agents import create_agent

from .config import DEFAULT_MODEL
from .middleware import MemoryMiddleware
from .prompt import SYSTEM_PROMPT
from .states import WebAgentState
from .tools import utc_now, calculator, open_page, read_page

graph = create_agent(
    model=DEFAULT_MODEL,
    tools=[utc_now, calculator, open_page, read_page],
    middleware=[MemoryMiddleware()],
    state_schema=WebAgentState,
    system_prompt=SYSTEM_PROMPT,
    name="simple_agent",
)
